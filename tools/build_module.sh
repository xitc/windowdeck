#!/bin/sh
set -eu
project_dir=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
sdk_path=${ANDROID_SDK_ROOT:-${ANDROID_HOME:-/opt/homebrew/share/android-commandlinetools}}
build_tools="$sdk_path/build-tools/${BUILD_TOOLS_VERSION:-35.0.0}"
if [ -n "${JAVA_HOME:-}" ]; then
 java_bin="$JAVA_HOME/bin"
elif [ -x /opt/homebrew/opt/openjdk/bin/javac ]; then
 java_bin=/opt/homebrew/opt/openjdk/bin
else
 java_bin=$(dirname "$(command -v javac)")
fi
key="$project_dir/build/windowdeck-test.keystore"
expected=a9b3625015d7023dd3e979e871e93a33f83cfcaa7090664348d01a8a23c572ae
if [ ! -r "$key" ]; then
 printf '%s\n' 'Restore the WindowDeck release keystore before building' >&2
 exit 1
fi
fingerprint=$("$java_bin/keytool" -J-Duser.language=en -J-Duser.country=US -list -v -keystore "$key" -storepass android -alias windowdeck)
actual=$(printf '%s\n' "$fingerprint" | sed -n 's/^[[:space:]]*SHA256: //p' | tr -d ':' | tr 'A-F' 'a-f')
if [ "$actual" != "$expected" ]; then
 printf '%s\n' "WindowDeck release certificate mismatch: ${actual:-missing}" >&2
 exit 1
fi
xposed_api=${XPOSED_API:-}
if [ -z "$xposed_api" ] && [ -d "$HOME/.gradle/caches/modules-2/files-2.1/de.robv.android.xposed/api/82" ]; then
 xposed_api=$(find "$HOME/.gradle/caches/modules-2/files-2.1/de.robv.android.xposed/api/82" -name api-82.jar -print | head -n 1)
fi
if [ ! -f "$xposed_api" ]; then
 printf '%s\n' 'Set XPOSED_API to the local Xposed API 82 jar.' >&2
 exit 1
fi
manifest="$project_dir/module/AndroidManifest.xml"
application_id=$(sed -n 's/.* package="\([^"]*\)".*/\1/p' "$manifest")
if [ "$#" -ne 0 ]; then
 if [ "$#" -ne 2 ] || [ "$1" != --application-id ]; then
  printf '%s\n' 'Usage: build_module.sh [--application-id dev.windowdeck.app|io.github.xitc.windowdeck]' >&2
  exit 1
 fi
 application_id=$2
fi
case "$application_id" in
 dev.windowdeck.app|io.github.xitc.windowdeck) ;;
 *) printf '%s\n' 'Unsupported application ID' >&2; exit 1;;
esac
version=$(sed -n 's/.*android:versionName="\([^"]*\)".*/\1/p' "$manifest")
code=$(sed -n 's/.*android:versionCode="\([^"]*\)".*/\1/p' "$manifest")
case "$version" in ''|*[!a-zA-Z0-9.-]*) printf '%s\n' 'Invalid APK version' >&2; exit 1;; esac
case "$code" in ''|*[!0-9]*) printf '%s\n' 'Invalid versionCode' >&2; exit 1;; esac
case "$version" in
 *-dev.*)
  devcode=${version##*-dev.}
  if [ "$devcode" != "$code" ]; then
   printf '%s\n' "versionName $version must end with -dev.$code" >&2
   exit 1
  fi
  ;;
esac
# Compilation is disposable and never writes a versioned candidate directory.
# A unique directory also isolates simultaneous builds of the same identity.
scratch="$project_dir/build/scratch/$application_id"
mkdir -p "$scratch"
out=$(mktemp -d "$scratch/build.XXXXXXXX")
mkdir -p "$out/classes" "$out/dex" "$out/gen"
# Only the generated manifest varies; Java source and Xposed entry stay fixed.
sed -e "s/ package=\"[^\"]*\"/ package=\"$application_id\"/" \
    -e 's/${applicationId}/'"$application_id"'/g' "$manifest" > "$out/AndroidManifest.xml"
"$build_tools/aapt2" compile --dir "$project_dir/module/res" -o "$out/resources.zip"
"$build_tools/aapt2" link -o "$out/base.apk" -I "$sdk_path/platforms/android-35/android.jar" --manifest "$out/AndroidManifest.xml" --custom-package io.github.xitc.windowdeck --java "$out/gen" -A "$project_dir/module/assets" "$out/resources.zip"
mkdir -p "$out/gen/io/github/xitc/windowdeck"
build_info="$project_dir/module/assets/windowdeck/BUILD_INFO.json"
commit=""
if [ -f "$build_info" ]; then
 commit=$(sed -n 's/^[[:space:]]*"git_head": "\([0-9a-f]*\)".*$/\1/p' "$build_info")
fi
if [ -z "$commit" ]; then commit=$(git -C "$project_dir" rev-parse HEAD 2>/dev/null || true); fi
case "$commit" in ''|*[!0-9a-f]*) commit=unknown ;; esac
case ${#commit} in 40|64) ;; *) commit=unknown ;; esac
cat > "$out/gen/io/github/xitc/windowdeck/Version.java" <<EOF
package io.github.xitc.windowdeck;
/** Generated by tools/build_module.sh from AndroidManifest.xml. */
final class Version {
 static final int CODE = $code;
 static final String NAME = "$version";
 static final String COMMIT = "$commit";
 private Version() {}
}
EOF
cat > "$out/gen/io/github/xitc/windowdeck/BuildIdentity.java" <<EOF
package io.github.xitc.windowdeck;
/** Generated installation identity. Never derive this from a hooked host Context. */
final class BuildIdentity {
 static final String APPLICATION_ID = "$application_id";
 static final String STATE_URI = "content://$application_id.state";
 private BuildIdentity() {}
}
EOF
find "$project_dir/module/src" "$out/gen" -name '*.java' > "$out/sources.list"
"$java_bin/javac" --release 8 -Xlint:-options -classpath "$sdk_path/platforms/android-35/android.jar:$xposed_api" -d "$out/classes" @"$out/sources.list"
"$java_bin/jar" cf "$out/classes.jar" -C "$out/classes" .
"$build_tools/d8" --min-api 35 --lib "$sdk_path/platforms/android-35/android.jar" --classpath "$xposed_api" --output "$out/dex" "$out/classes.jar"
cp "$out/base.apk" "$out/unsigned.apk"
(cd "$out/dex" && zip -q "$out/unsigned.apk" classes.dex)
"$build_tools/zipalign" -f -p 4 "$out/unsigned.apk" "$out/aligned.apk"
"$build_tools/apksigner" sign --ks "$key" --ks-key-alias windowdeck --ks-pass pass:android --key-pass pass:android --out "$out/windowdeck-v$version.apk" "$out/aligned.apk"
certs=$("$build_tools/apksigner" verify --print-certs "$out/windowdeck-v$version.apk")
actual=$(printf '%s\n' "$certs" | sed -n 's/^Signer #[0-9][0-9]* certificate SHA-256 digest: //p')
if [ "$actual" != "$expected" ]; then
 printf '%s\n' 'Signed APK certificate differs from the WindowDeck release certificate' >&2
 exit 1
fi
printf '%s\n' "$out/windowdeck-v$version.apk"
